/**
 * TypeGuard - Compilation & Analysis Report Export Utility
 * Generates downloadable reports in Markdown/Text, JSON, and CSV formats
 */

export function generateMarkdownReport(analysis) {
  if (!analysis) return '';

  const timestamp = new Date().toISOString();
  const statusStr = analysis.success ? 'PASSED (TYPE-SAFE)' : 'FAILED (ERRORS DETECTED)';

  let md = `# TypeGuard - Static Type Checking Analysis Report
Generated: ${timestamp}
Overall Status: ${statusStr}

---

## 1. Summary Statistics
- **Total Lines**: ${analysis.stats.lineCount}
- **Total Tokens**: ${analysis.stats.tokenCount}
- **Variables Declared**: ${analysis.stats.declarationCount}
- **Syntax Analysis**: ${analysis.stats.syntaxStatus}
- **Type Checking**: ${analysis.stats.typeStatus}
- **Total Diagnostics**: ${analysis.stats.diagnosticCount} (${analysis.stats.errorCount} Errors, ${analysis.stats.warningCount} Warnings)

---

## 2. Source Code
\`\`\`text
${analysis.sourceCode}
\`\`\`

---

## 3. Compiler Pipeline Stages
`;

  Object.values(analysis.stages).forEach(stage => {
    const symbol = stage.status === 'passed' ? '✓' : (stage.status === 'failed' ? '✗' : '○');
    md += `- **[${symbol}] ${stage.name}**: ${stage.status.toUpperCase()} - ${stage.detail || stage.description}\n`;
  });

  md += `\n---\n\n## 4. Symbol Table\n`;
  if (analysis.symbolTable.length === 0) {
    md += `*No variables declared in the program.*\n`;
  } else {
    md += `| Variable | Type | Initial Value | Line | Scope | Initialized? | Memory Offset |\n`;
    md += `| :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n`;
    analysis.symbolTable.forEach(sym => {
      md += `| \`${sym.name}\` | \`${sym.type}\` | ${sym.initialValue} | ${sym.line} | ${sym.scope} | ${sym.isInitialized ? 'Yes' : 'No'} | 0x${sym.memoryOffset.toString(16).padStart(4, '0')} |\n`;
    });
  }

  md += `\n---\n\n## 5. Diagnostics & Type Errors\n`;
  if (analysis.diagnostics.length === 0) {
    md += `*No errors or warnings. Program passed static type checking perfectly!*\n`;
  } else {
    analysis.diagnostics.forEach((d, idx) => {
      md += `### ${idx + 1}. [${d.code}] ${d.type} (Line ${d.line}, Col ${d.col})\n`;
      md += `- **Severity**: ${d.severity.toUpperCase()}\n`;
      md += `- **Message**: ${d.message}\n`;
      if (d.expectedType) md += `- **Expected Type**: \`${d.expectedType}\`\n`;
      if (d.actualType) md += `- **Actual Type**: \`${d.actualType}\`\n`;
      if (d.explanation) md += `- **Explanation**: ${d.explanation}\n`;
      if (d.suggestion) md += `- **Suggestion**: ${d.suggestion}\n`;
      md += `\n`;
    });
  }

  if (analysis.intermediateCode && analysis.intermediateCode.instructions.length > 0) {
    md += `---\n\n## 6. Generated Intermediate Code (Three-Address Code)\n\`\`\`text\n`;
    analysis.intermediateCode.instructions.forEach(instr => {
      md += `${instr}\n`;
    });
    md += `\`\`\`\n`;
  }

  md += `\n---\n*Report generated by TypeGuard — Compiler Design Mini Project*`;
  return md;
}

export function downloadFile(content, fileName, mimeType) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function downloadJsonReport(analysis) {
  if (!analysis) return;
  const jsonStr = JSON.stringify(analysis, null, 2);
  downloadFile(jsonStr, `typeguard-analysis-${Date.now()}.json`, 'application/json');
}

export function downloadSymbolTableCsv(symbolTable) {
  if (!symbolTable || symbolTable.length === 0) return;
  const headers = ['Variable', 'Type', 'Initial Value', 'Line', 'Scope', 'Initialized', 'Memory Offset (Bytes)'];
  const rows = symbolTable.map(s => [
    s.name,
    s.type,
    `"${s.initialValue.replace(/"/g, '""')}"`,
    s.line,
    s.scope,
    s.isInitialized ? 'true' : 'false',
    s.memoryOffset
  ]);

  const csv = [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
  downloadFile(csv, `typeguard-symbol-table-${Date.now()}.csv`, 'text/csv');
}
